/**
 * Judge calibration: `npm run eval:judge-calibration -w @wanderly/evals [-- options]`.
 *
 * - `--export <results dir> [--limit 25]`: appends judged outputs of a real run to
 *   evals/datasets/judge-calibration.yaml with empty human labels (see the file's instructions).
 * - default: computes judge–human agreement and Cohen's kappa per property over the items both
 *   graded; `--write` also updates the calibration section of docs/EVALUATIONS.md.
 */
import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';
import { AgentResponseSchema } from '@wanderly/contracts';
import { parse, stringify } from 'yaml';
import { z } from 'zod';
import type { LlmMessage } from '../../services/api/src/domain/ports/llm.js';
import { replaceSection } from '../report/agent-report.js';
import { retrievedContext } from '../runner/agent-harness.js';
import { cohensKappa, type Agreement } from './agreement.js';
import { JUDGE_PROMPT_VERSION } from './judge-prompts.js';

const EVALS_DIR = fileURLToPath(new URL('..', import.meta.url));
const REPO_DIR = path.resolve(EVALS_DIR, '..');
const DATASET_FILE = path.join(EVALS_DIR, 'datasets', 'judge-calibration.yaml');
const EVALUATIONS_DOC = path.join(REPO_DIR, 'docs', 'EVALUATIONS.md');
export const CALIBRATION_START = '<!-- judge-calibration:start -->';
export const CALIBRATION_END = '<!-- judge-calibration:end -->';

const FitSchema = z.union([z.literal(0), z.literal(1), z.literal(2)]).nullable();

export const CalibrationItemSchema = z.strictObject({
  id: z.string().min(1),
  caseId: z.string().min(1),
  rep: z.int().min(1),
  source: z.string().min(1),
  judgeModel: z.string().nullable(),
  judgePromptVersion: z.string(),
  userTurns: z.array(z.string()).min(1),
  response: AgentResponseSchema,
  retrievedContext: z.array(z.string()),
  judge: z.strictObject({
    faithful: z.union([z.literal(0), z.literal(1)]).nullable(),
    request_fit: FitSchema,
  }),
  human: z.strictObject({ faithful: z.boolean().nullable(), request_fit: FitSchema }),
  notes: z.string(),
});
export type CalibrationItem = z.infer<typeof CalibrationItemSchema>;

export const CalibrationSetSchema = z.strictObject({
  version: z.literal(1),
  items: z.array(CalibrationItemSchema),
});

export interface CalibrationReport {
  readonly items: number;
  readonly labelled: number;
  readonly faithful: Agreement;
  readonly requestFit: Agreement;
}

/** Agreement per property over the items both the judge and the human graded. */
export function computeCalibration(items: readonly CalibrationItem[]): CalibrationReport {
  const faithfulPairs = items.flatMap((item) =>
    item.judge.faithful === null || item.human.faithful === null
      ? []
      : [[item.judge.faithful, item.human.faithful ? 1 : 0] as const],
  );
  const fitPairs = items.flatMap((item) =>
    item.judge.request_fit === null || item.human.request_fit === null
      ? []
      : [[item.judge.request_fit, item.human.request_fit] as const],
  );
  return {
    items: items.length,
    labelled: items.filter(
      (item) => item.human.faithful !== null || item.human.request_fit !== null,
    ).length,
    faithful: cohensKappa(faithfulPairs),
    requestFit: cohensKappa(fitPairs),
  };
}

export function renderCalibration(report: CalibrationReport): string {
  if (report.labelled === 0) {
    return `No human labels yet (${report.items} item(s) exported, 0 labelled): the judge is not calibrated, and its scores are a development signal only.`;
  }
  const line = (name: string, value: Agreement) =>
    `| ${name} | ${value.n} | ${(value.agreement * 100).toFixed(1)} % | ${value.kappa === null ? 'undefined' : value.kappa.toFixed(2)} |`;
  return [
    `${report.labelled} of ${report.items} item(s) labelled by a human. Generated by \`npm run eval:judge-calibration -w @wanderly/evals -- --write\`; do not edit by hand.`,
    '',
    '| Property | Items | Agreement | Cohen κ |',
    '|---|---:|---:|---:|',
    line('faithful (all claims supported)', report.faithful),
    line('request fit (0 / 1 / 2)', report.requestFit),
  ].join('\n');
}

const TraceSchema = z.object({
  case: z.object({ id: z.string(), turns: z.array(z.string()) }),
  rep: z.int(),
  judge: z.object({
    scores: z
      .object({ faithful: z.number().nullable(), request_fit: z.number().nullable() })
      .optional(),
  }),
  turns: z.array(z.object({ response: z.unknown(), messages: z.array(z.custom<LlmMessage>()) })),
});

async function exportItems(runDir: string, limit: number, existing: readonly CalibrationItem[]) {
  const summary = JSON.parse(await readFile(path.join(runDir, 'summary.json'), 'utf8')) as {
    judgeModel?: string | null;
    judgePromptVersion?: string;
  };
  const files = (await readdir(path.join(runDir, 'traces')))
    .filter((name) => name.endsWith('.json'))
    .sort();
  const known = new Set(existing.map((item) => item.id));
  const items: CalibrationItem[] = [];
  for (const file of files) {
    if (items.length >= limit) break;
    const trace = TraceSchema.parse(
      JSON.parse(await readFile(path.join(runDir, 'traces', file), 'utf8')),
    );
    const scores = trace.judge.scores;
    const response = AgentResponseSchema.safeParse(trace.turns.at(-1)?.response);
    if (scores === undefined || !response.success) continue;
    const id = `${path.basename(runDir)}/${trace.case.id}_rep${trace.rep}`;
    if (known.has(id)) continue;
    items.push({
      id,
      caseId: trace.case.id,
      rep: trace.rep,
      source: path.basename(runDir),
      judgeModel: summary.judgeModel ?? null,
      judgePromptVersion: summary.judgePromptVersion ?? JUDGE_PROMPT_VERSION,
      userTurns: trace.case.turns,
      response: response.data,
      retrievedContext: retrievedContext(trace.turns),
      judge: {
        faithful: scores.faithful === null ? null : scores.faithful >= 1 ? 1 : 0,
        request_fit:
          scores.request_fit === null ? null : (Math.round(scores.request_fit * 2) as 0 | 1 | 2),
      },
      human: { faithful: null, request_fit: null },
      notes: '',
    });
  }
  return items;
}

async function main(): Promise<void> {
  const { values } = parseArgs({
    options: {
      export: { type: 'string' },
      limit: { type: 'string', default: '25' },
      write: { type: 'boolean', default: false },
    },
  });
  const text = await readFile(DATASET_FILE, 'utf8');
  const set = CalibrationSetSchema.parse(parse(text));
  if (values.export !== undefined) {
    const added = await exportItems(path.resolve(values.export), Number(values.limit), set.items);
    const header = text.slice(0, text.indexOf('version: 1'));
    await writeFile(
      DATASET_FILE,
      `${header}${stringify({ version: 1, items: [...set.items, ...added] })}`,
    );
    console.log(
      `Added ${added.length} item(s) to ${path.relative(REPO_DIR, DATASET_FILE)}; now label them.`,
    );
    return;
  }
  const rendered = renderCalibration(computeCalibration(set.items));
  console.log(rendered);
  if (values.write) {
    const document = await readFile(EVALUATIONS_DOC, 'utf8');
    await writeFile(
      EVALUATIONS_DOC,
      replaceSection(document, rendered, CALIBRATION_START, CALIBRATION_END),
    );
  }
}

if (
  process.argv[1] !== undefined &&
  fileURLToPath(import.meta.url) === path.resolve(process.argv[1])
) {
  main().catch((error: unknown) => {
    console.error(error instanceof Error ? error.message : error);
    process.exit(2);
  });
}
