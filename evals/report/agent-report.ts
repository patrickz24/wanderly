import { LOWER_IS_BETTER, type AgentMetric } from '../scorers/agent-metrics.js';
import type { RunSummary } from '../scorers/agent-summary.js';
import type { GateResult } from '../runner/agent-gate.js';

/** Markdown report of an agent evaluation run (job summary, docs section, results folder). */

export const AGENT_RESULTS_START = '<!-- agent-results:start -->';
export const AGENT_RESULTS_END = '<!-- agent-results:end -->';

export interface ReportMeta {
  readonly generatedAt: string;
  readonly mode: string;
  readonly agentModel: string;
  readonly judgeModel: string | null;
  readonly promptVersion: string;
  readonly gitSha: string | null;
  readonly command: string;
  readonly infraFailures: Readonly<Record<string, number>>;
  readonly abortedReason: string | null;
}

const pct = (value: number): string => (value * 100).toFixed(1);
const usd = (value: number): string => `$${value.toFixed(4)}`;

export function renderMetricsTable(summary: RunSummary): string {
  const header = ['| Metric | Value | 95 % CI | n cases | Better |', '|---|---:|---:|---:|---|'];
  const lines = Object.entries(summary.metrics).flatMap(([metric, value]) =>
    value === undefined
      ? []
      : [
          `| ${metric} | ${pct(value.mean)} | ${pct(value.interval.low)}–${pct(value.interval.high)} | ${value.n} | ${
            LOWER_IS_BETTER.has(metric as AgentMetric) ? 'lower' : 'higher'
          } |`,
        ],
  );
  return [...header, ...lines].join('\n');
}

export function renderCategoryTable(summary: RunSummary): string {
  const columns = [
    'response_type_correct',
    'guardrail_pass',
    'constraint_fit',
    'citation_integrity',
  ];
  const header = [
    `| Category | Cases | ${columns.join(' | ')} |`,
    `|---|---:|${columns.map(() => '---:').join('|')}|`,
  ];
  const lines = Object.entries(summary.byCategory).map(([category, values]) => {
    const cells = columns.map((column) => {
      const value = values?.[column];
      return value === undefined ? '–' : pct(value);
    });
    return `| ${category} | ${values?.['cases'] ?? 0} | ${cells.join(' | ')} |`;
  });
  return [...header, ...lines].join('\n');
}

export function renderGate(gate: GateResult, title: string): string {
  const lines = [
    `**${title}: ${gate.verdict.toUpperCase()}**${gate.pendingSoftGates > 0 ? ` (${gate.pendingSoftGates} soft gate(s) pending first baseline)` : ''}`,
    '',
    '| Gate | Metric | Threshold | Actual | Outcome |',
    '|---|---|---|---:|---|',
    ...gate.checks.map(
      (item) =>
        `| ${item.kind} | ${item.metric} | ${item.threshold} | ${item.actual === null ? '–' : item.actual.toFixed(3)} | ${item.outcome} |`,
    ),
  ];
  return lines.join('\n');
}

export function renderAgentReport(
  meta: ReportMeta,
  summary: RunSummary,
  gates: readonly { readonly title: string; readonly result: GateResult }[],
): string {
  const failures = Object.entries(meta.infraFailures);
  return [
    `Run of ${meta.generatedAt.slice(0, 10)} (${meta.mode}), agent \`${meta.agentModel}\`, judge ${
      meta.judgeModel === null ? 'not run' : `\`${meta.judgeModel}\``
    }, prompt \`${meta.promptVersion}\`${meta.gitSha === null ? '' : `, commit \`${meta.gitSha.slice(0, 7)}\``}.`,
    `${summary.cases} cases × ${summary.reps} rep(s), ${summary.scoredRows} scored runs. Generated by \`${meta.command}\`; do not edit by hand.`,
    ...(meta.abortedReason === null ? [] : ['', `**Run aborted early: ${meta.abortedReason}.**`]),
    '',
    'Statuses: ' +
      Object.entries(summary.statuses)
        .map(([status, count]) => `${status} ${count}`)
        .join(', ') +
      `. Infrastructure failures (not scored, see errors.jsonl): ${
        failures.length === 0
          ? 'none'
          : failures.map(([name, count]) => `${name} ${count}`).join(', ')
      }.`,
    '',
    'Metrics in % (mean over cases of the mean over reps; 95 % bootstrap interval over cases):',
    '',
    renderMetricsTable(summary),
    '',
    `Noise floor of a pass rate at this size: about ±${pct(summary.noiseFloor)} points (1/√(cases × reps)).`,
    '',
    'By category:',
    '',
    renderCategoryTable(summary),
    '',
    'Cost and latency (agent and judge counted separately, from API usage and the shared price table):',
    '',
    '| Agent cost | Judge cost | Agent cost / run | Latency p50 | Latency p95 | Steps (mean / max) | Infra retries |',
    '|---:|---:|---:|---:|---:|---:|---:|',
    `| ${usd(summary.perf.agentCostUsd)} | ${usd(summary.perf.judgeCostUsd)} | ${usd(summary.perf.meanAgentCostPerRunUsd)} | ${(summary.perf.latencyP50Ms / 1000).toFixed(1)} s | ${(summary.perf.latencyP95Ms / 1000).toFixed(1)} s | ${summary.perf.meanSteps.toFixed(1)} / ${summary.perf.maxSteps} | ${summary.perf.retries} |`,
    ...gates.flatMap((gate) => ['', renderGate(gate.result, gate.title)]),
  ].join('\n');
}

/** Replaces what is between two markers, keeping the hand-written text around them. */
export function replaceSection(
  document: string,
  content: string,
  start: string = AGENT_RESULTS_START,
  end: string = AGENT_RESULTS_END,
): string {
  const from = document.indexOf(start);
  const to = document.indexOf(end);
  if (from === -1 || to === -1 || to < from) throw new Error(`markers ${start} … ${end} not found`);
  return `${document.slice(0, from + start.length)}\n\n${content.trim()}\n\n${document.slice(to)}`;
}
