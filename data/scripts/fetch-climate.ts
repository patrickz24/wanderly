/**
 * Computes monthly climate normals for every destination from the Open-Meteo Historical Weather
 * API (daily ERA5-Seamless reanalysis, 2015-2024) and writes data/climate/<id>.yaml.
 *
 * Usage: npx tsx --conditions=development data/scripts/fetch-climate.ts [--only <id>] [--refresh]
 *
 * Raw responses are cached in data/raw/open-meteo/ (gitignored) keyed by request URL, so a re-run
 * is deterministic and offline; `--refresh` downloads again. The free API is for non-commercial
 * use and its data is CC BY 4.0: attribution is written next to the data (see data/README.md).
 */
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { z } from 'zod';
import { parseCliArgs } from './cli-args.js';
import {
  CLIMATE_ATTRIBUTION,
  CLIMATE_LICENSE,
  CLIMATE_MODEL,
  CLIMATE_PERIOD,
  CLIMATE_PROVIDER,
  type ClimateFile,
  ClimateFileSchema,
  OpenMeteoDailySchema,
  aggregateMonthlyNormals,
} from './climate.js';
import { type Destination, loadDestinations, selectDestinations } from './destinations.js';
import { RequestPacer, getJson } from './http.js';
import { climatePath, rawOpenMeteoPath } from './paths.js';
import { readJsonIfExists, writeYamlFile } from './yaml-io.js';

const ARCHIVE_API = 'https://archive-api.open-meteo.com/v1/archive';
const DAILY_VARIABLES = ['temperature_2m_max', 'temperature_2m_min', 'precipitation_sum'];

const CachedResponseSchema = z.object({
  request_url: z.string(),
  retrieved_at: z.string(),
  response: z.unknown(),
});

function archiveUrl(destination: Destination): URL {
  const url = new URL(ARCHIVE_API);
  url.searchParams.set('latitude', String(destination.climate_point.lat));
  url.searchParams.set('longitude', String(destination.climate_point.lon));
  url.searchParams.set('start_date', CLIMATE_PERIOD.start);
  url.searchParams.set('end_date', CLIMATE_PERIOD.end);
  url.searchParams.set('daily', DAILY_VARIABLES.join(','));
  url.searchParams.set('timezone', 'auto');
  url.searchParams.set('models', CLIMATE_MODEL);
  return url;
}

/**
 * Open-Meteo weighs a request by its volume (a 10-year, 3-variable daily series counts as dozens
 * of calls) against a limit of 600 calls per minute on the free tier: one request every 15 s keeps
 * a full run well below it.
 */
const pacer = new RequestPacer(15_000);

async function loadDaily(
  destination: Destination,
  refresh: boolean,
): Promise<{ response: unknown; retrievedAt: string; origin: string }> {
  const url = archiveUrl(destination);
  const file = rawOpenMeteoPath(destination.id);
  const cached = CachedResponseSchema.safeParse(await readJsonIfExists(file));
  if (!refresh && cached.success && cached.data.request_url === url.href) {
    return {
      response: cached.data.response,
      retrievedAt: cached.data.retrieved_at,
      origin: 'cache',
    };
  }
  const response = await getJson(url, { pacer, timeoutMs: 120_000 });
  const retrievedAt = new Date().toISOString();
  await mkdir(path.dirname(file), { recursive: true });
  await writeFile(
    file,
    JSON.stringify({ request_url: url.href, retrieved_at: retrievedAt, response }),
    'utf8',
  );
  return { response, retrievedAt, origin: 'fetched' };
}

async function main(): Promise<void> {
  const options = parseCliArgs(process.argv.slice(2), ['--refresh']);
  const destinations = selectDestinations(await loadDestinations(), options.only);
  for (const destination of destinations) {
    const { response, retrievedAt, origin } = await loadDaily(
      destination,
      options.flags.has('--refresh'),
    );
    const parsed = OpenMeteoDailySchema.safeParse(response);
    if (!parsed.success) {
      throw new Error(
        `Unexpected Open-Meteo response for ${destination.id}: ${parsed.error.message}`,
      );
    }
    const data = parsed.data;
    const { months, missingDays } = aggregateMonthlyNormals(data.daily);
    const climate: ClimateFile = {
      id: destination.id,
      provider: CLIMATE_PROVIDER,
      model: CLIMATE_MODEL,
      period: { ...CLIMATE_PERIOD },
      point: { ...destination.climate_point },
      grid_cell: { lat: data.latitude, lon: data.longitude, elevation_m: data.elevation },
      timezone: data.timezone,
      license: CLIMATE_LICENSE,
      attribution: CLIMATE_ATTRIBUTION,
      retrieved_at: retrievedAt,
      missing_days: missingDays,
      months,
    };
    await writeYamlFile(
      climatePath(destination.id),
      ClimateFileSchema.parse(climate),
      'Generated by data/scripts/fetch-climate.ts from Open-Meteo daily data. Do not edit by hand.',
    );
    const july = months[6];
    console.log(
      `${destination.id.padEnd(20)} ${origin}: grid ${data.latitude},${data.longitude} ` +
        `(${data.elevation} m), ${data.daily.time.length} days, ${missingDays} missing; ` +
        `July ${july?.avg_high_c ?? '?'}/${july?.avg_low_c ?? '?'} °C`,
    );
  }
}

main().catch((error: unknown) => {
  console.error(error instanceof Error ? error.message : error);
  process.exitCode = 1;
});
